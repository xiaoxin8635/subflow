/**
 * @file ASS 字幕文件生成器
 * @description 将 Style.config（前端预览同一份契约）+ Transcript.segments 编译为 ASS 文件，
 *              供 FFmpeg `ass` 滤镜烧录。坐标基准 PlayRes 1920x1080，
 *              fontSize 为 @1080p 高度百分比，marginV/outlineWidth 为 @1080p 像素。
 *              关键词高亮使用行内覆盖标签 {\c} 实现（与前端预览的 highlight 行为对齐）。
 */

/** 样式配置契约（与 subtitle-overlay.tsx 中的定义一致） */
export interface AssStyleConfig {
  fontFamily: string;
  /** 字号：相对 1080p 高度的百分比 */
  fontSize: number;
  /** 主颜色 #RRGGBB */
  primaryColor: string;
  /** 描边颜色，空串 = 不描边 */
  outlineColor: string;
  /** 描边宽度（px @1080p） */
  outlineWidth: number;
  /** 垂直位置 */
  position: "top" | "center" | "bottom";
  /** 垂直边距（px @1080p） */
  marginV: number;
  /** 关键词高亮色，空串 = 不高亮 */
  highlight: string;
}

/** 字幕段（生成 Dialogue 行所需最小结构） */
export interface AssSegment {
  /** 开始时间（秒） */
  start: number;
  /** 结束时间（秒） */
  end: number;
  text: string;
  keywords?: string[];
}

/** ASS 脚本分辨率基准（与样式契约的 1080p 基准一致） */
const PLAY_RES_X = 1920;
const PLAY_RES_Y = 1080;

/**
 * 默认样式配置（白字黑边、底部）：样式记录缺失/损坏时的兜底，
 * 烧录流水线与 ASS 字幕下载接口共用，保证行为一致
 */
export const DEFAULT_ASS_CONFIG: AssStyleConfig = {
  fontFamily: "Noto Sans SC",
  fontSize: 5.2,
  primaryColor: "#FFFFFF",
  outlineColor: "#000000",
  outlineWidth: 3,
  position: "bottom",
  marginV: 90,
  highlight: "",
};

/**
 * #RRGGBB → ASS 颜色 &HAABBGGRR（ASS 为 BGR 字节序，AA=00 全不透明）
 * @param hex 十六进制颜色
 * @param alpha 透明度（00 = 不透明）
 */
function hexToAss(hex: string, alpha = "00"): string {
  const m = hex.replace("#", "").match(/^([0-9a-fA-F]{6})$/);
  if (!m) return "&H00FFFFFF"; // 非法颜色兜底白色
  const rr = m[1].slice(0, 2).toUpperCase();
  const gg = m[1].slice(2, 4).toUpperCase();
  const bb = m[1].slice(4, 6).toUpperCase();
  return `&H${alpha}${bb}${gg}${rr}`;
}

/**
 * 秒 → ASS 时间戳 H:MM:SS.CS（厘秒两位）
 * @param t 秒
 */
function toAssTime(t: number): string {
  const clamped = Math.max(0, t);
  const h = Math.floor(clamped / 3600);
  const m = Math.floor((clamped % 3600) / 60);
  const s = Math.floor(clamped % 60);
  const cs = Math.round((clamped - Math.floor(clamped)) * 100) % 100;
  return `${h}:${String(m).padStart(2, "0")}:${String(s).padStart(2, "0")}.${String(cs).padStart(2, "0")}`;
}

/** ASS 文本转义（换行 → \N；抑制覆盖标签花括号） */
function escapeAssText(text: string): string {
  return text.replace(/[{}]/g, "").replace(/\r?\n/g, "\\N");
}

/**
 * 生成关键词高亮的 Dialogue 文本（{\c} 覆盖标签包裹关键词）
 * @param text   原文本（已转义）
 * @param keywords 关键词列表
 * @param primaryAss 主色 ASS
 * @param highlightAss 高亮色 ASS（空串则原样返回）
 */
function applyHighlight(
  text: string,
  keywords: string[],
  primaryAss: string,
  highlightAss: string,
): string {
  if (!highlightAss || keywords.length === 0) return text;
  let out = text;
  for (const kw of keywords) {
    if (!kw) continue;
    const escapedKw = kw.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    // 用函数形式替换，避免 kw 中含 $ 触发特殊替换模式（如 $&）
    out = out.replace(escapedKw, () => `{\\c${highlightAss}}${kw}{\\c${primaryAss}}`);
  }
  return out;
}

/**
 * 编译完整 ASS 文件内容
 * @param config   样式配置
 * @param segments 字幕分段
 * @returns ASS 文件文本（UTF-8，含 BOM 由调用方决定；libass 读 UTF-8 无 BOM 即可）
 */
export function buildAss(config: AssStyleConfig, segments: AssSegment[]): string {
  // Alignment（ASS 数字小键盘布局）：bottom=2 下中 / center=5 居中 / top=8 上中
  const alignment = config.position === "top" ? 8 : config.position === "center" ? 5 : 2;
  // center 时 marginV 不参与定位（居中锚点），仅 top/bottom 使用
  const marginV = config.position === "center" ? 0 : Math.max(0, Math.round(config.marginV));
  const fontSizePx = Math.max(8, Math.round((config.fontSize / 100) * PLAY_RES_Y));
  const outline = config.outlineColor && config.outlineWidth > 0 ? Math.round(config.outlineWidth) : 0;

  const primaryAss = hexToAss(config.primaryColor);
  const outlineAss = config.outlineColor ? hexToAss(config.outlineColor) : "&H00000000";
  const highlightAss = config.highlight ? hexToAss(config.highlight) : "";
  const fontName = config.fontFamily;

  const header = [
    "[Script Info]",
    "; Generated by SubFlow",
    "ScriptType: v4.00+",
    `PlayResX: ${PLAY_RES_X}`,
    `PlayResY: ${PLAY_RES_Y}`,
    "WrapStyle: 2", // 不自动换行（保留 \N 手动换行），超出宽度自动缩排
    "ScaledBorderAndShadow: yes",
    "",
    "[V4+ Styles]",
    "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding",
    `Style: Default,${fontName},${fontSizePx},${primaryAss},&H000000FF,${outlineAss},&H00000000,1,0,0,0,100,100,0,0,1,${outline},0,${alignment},60,60,${marginV},1`,
    "",
    "[Events]",
    "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text",
  ].join("\n");

  const dialogues = segments
    .filter((s) => Number.isFinite(s.start) && Number.isFinite(s.end) && s.end > s.start && s.text?.trim())
    .map((s) => {
      const raw = escapeAssText(s.text.trim());
      const text = applyHighlight(raw, s.keywords ?? [], primaryAss, highlightAss);
      return `Dialogue: 0,${toAssTime(s.start)},${toAssTime(s.end)},Default,,0,0,0,,${text}`;
    });

  return `${header}\n${dialogues.join("\n")}\n`;
}
